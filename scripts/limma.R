args <- commandArgs(trailingOnly=TRUE)
suppressPackageStartupMessages(library(limma))
x <- as.matrix(read.delim(args[1], row.names=1, check.names=FALSE))
stopifnot(identical(colnames(x), c('H1','H2','H3','L1','L2','L3')))
group <- factor(c('H','H','H','L','L','L'), levels=c('L','H'))
design <- model.matrix(~group)
fit <- eBayes(lmFit(x, design), trend=TRUE)
tab <- topTable(fit, coef='groupH', number=Inf, sort.by='none', adjust.method='BH')
tab <- cbind(protein_group=rownames(tab), tab)
write.table(tab, args[2], sep='\t', quote=FALSE, row.names=FALSE)
writeLines(capture.output(sessionInfo()), args[3])
